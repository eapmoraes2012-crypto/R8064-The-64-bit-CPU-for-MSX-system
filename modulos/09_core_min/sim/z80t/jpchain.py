import sys; sys.argv=['x']
import z80rand as zr
zr.build()
def run(segs,end,tag,a0=0):
    img=bytearray(4096)
    for ad,bs in segs: img[ad:ad+len(bs)]=bytes(bs)
    init=dict(r=dict(a=a0,b=0,c=0,d=0,e=0,h=0x06,l=0,f=0),sp=0xC00)
    z,n=zr.expected(img,init,end)
    R,mem=zr.run_rtl(img,init,60*n+1500)
    print(tag,'B model=%02x rtl=%x'%(z.r['b'],R['R1']>>8))
