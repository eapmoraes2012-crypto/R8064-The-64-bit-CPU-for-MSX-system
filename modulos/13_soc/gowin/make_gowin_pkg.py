#!/usr/bin/env python3
# make_gowin_pkg.py - builds the Gowin EDA package of the cartridge (r8064_cart_top) from the sources:
#   <out>/src/r8064_cart_all.v  : all RTL listed in ../pnr/ys_cart.ys in ONE file, with the build macros of ys_cart.ys (-D...) as `define
#                                 and the .mem/.hex paths made absolute (Gowin resolves $readmemh paths unreliably)
#   <out>/src/*.mem, *.hex      : ROM images (uop, decoder, governor, monitor), copied from ../pnr
#   <out>/src/tangnano20k_cart.cst, r8064_cart.sdc, <out>/gowin_build.tcl, <out>/rodar_gowin.bat
# Usage: python3 make_gowin_pkg.py <out_dir> [<absolute path of out_dir/src as Gowin will see it, e.g. C:/Users/me/Documents/R8064_gowin/src/>]
import os, re, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__)); PNR = os.path.join(HERE, '..', 'pnr')
out = os.path.abspath(sys.argv[1]); src = os.path.join(out, 'src'); os.makedirs(src, exist_ok=True)
P = sys.argv[2] if len(sys.argv) > 2 else src.replace('\\', '/') + '/'
if not P.endswith('/'): P += '/'
first = open(os.path.join(PNR, 'ys_cart.ys'), encoding='utf-8').read().split('\n')[0]
defs = re.findall(r'-D(\w+)', first); files = [f for f in first.split() if f.endswith('.v')]
MEMS = ['gov_rom.mem', 'uop.mem', 'mainctrl.mem', 'rom_ed_a.mem', 'rom_ed_b.mem', 'amb_idx.mem', 'ctrl_b.mem']
o = ['// r8064_cart_all.v - GENERATED by modulos/13_soc/gowin/make_gowin_pkg.py: all RTL of the cartridge top (r8064_cart_top) in one file',
     '// for Gowin EDA, with the build macros of ys_cart.ys and absolute paths for the .mem/.hex files. Regenerate from the sources; do not edit.']
o += ['`define ' + d for d in defs] + ['']
for f in files:
    s = open(os.path.join(PNR, f), encoding='utf-8').read().replace('\r\n', '\n')
    for n in MEMS: s = s.replace('"%s"' % n, '"%s%s"' % (P, n))
    s = s.replace('INIT_PFX = "monitor_l"', 'INIT_PFX = "%smonitor_l"' % P)
    o += ['// ===================== %s =====================' % os.path.normpath(f).replace(os.sep, '/'), s]
open(os.path.join(src, 'r8064_cart_all.v'), 'w', newline='\r\n').write('\n'.join(o))
for n in MEMS + ['monitor_l%d.hex' % i for i in range(8)] + ['tangnano20k_cart.cst']: shutil.copy(os.path.join(PNR, n), src)
shutil.copy(os.path.join(HERE, 'r8064_cart.sdc'), src)
for n in ('gowin_build.tcl', 'rodar_gowin.bat'): shutil.copy(os.path.join(HERE, n), out)
print('package in', out, '| macros:', ' '.join(defs), '| files:', len(files), '| ROM path:', P)
