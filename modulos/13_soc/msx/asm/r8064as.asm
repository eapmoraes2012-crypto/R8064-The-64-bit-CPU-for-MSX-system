; ---------------------------------------------------------------- conditional assembly
isactive:                       ; NZ if every level of the IF stack is true
        ld a,(conddepth)
        or a
        jr z,ia_y
        ld b,a
        ld hl,condstk
ia_l:   ld a,(hl)
        or a
        ret z
        inc hl
        djnz ia_l
ia_y:   or 1
        ret

pushcond:                       ; A = value
        ld c,a
        ld a,(conddepth)
        cp 16
        jr nc,pc_over
        ld e,a
        ld d,0
        ld hl,condstk
        add hl,de
        ld (hl),c
        inc a
        ld (conddepth),a
        ret
pc_over: ld a,E_IF
        jp error

dir_if: call isactive
        jr nz,di_a
        xor a
        jp pushcond
di_a:   ld hl,di_trap           ; an error in the expression = "not known in pass 1"
        ld (evtrap),hl
        ld hl,(rest)
        call eval
        ld hl,0
        ld (evtrap),hl
        ld a,(known)
        or a
        jr z,di_trap
        ld hl,VAL
        call iszero8
        ld a,0
        jp z,pushcond
        inc a
        jp pushcond
di_trap: ld hl,0
        ld (evtrap),hl
        xor a
        call pushcond
        jp err_p1

dir_ifdef:
        ld c,1
        jr dif
dir_ifndef:
        ld c,0
dif:    call isactive
        jr nz,dif_a
        xor a
        jp pushcond
dif_a:  push bc
        ld hl,(rest)
        call skipsp
        ld de,NAMEBUF
        call getname0
        call skipsp
        ld a,(hl)
        or a
        ld a,0
        jr nz,dif_x             ; more text after the name: not a symbol
        call symfind            ; NZ = found
        ld a,0
        jr z,dif_x
        inc a
dif_x:  pop bc
dif_n:  xor c                   ; IFDEF: found; IFNDEF: not found
        xor 1
        jp pushcond

dir_else:
        ld a,(conddepth)
        or a
        jp z,pc_over
        dec a
        ld b,a                  ; outer levels all true?
        ld c,1
        ld hl,condstk
        or a
        jr z,de_t
de_l:   ld a,(hl)
        or a
        jr nz,de_n
        ld c,0
de_n:   inc hl
        djnz de_l
de_t:   ld a,(hl)               ; new = outer and not current
        or a
        ld a,0
        jr nz,de_s
        ld a,c
de_s:   ld (hl),a
        ret

dir_endif:
        ld a,(conddepth)
        or a
        jp z,pc_over
        dec a
        ld (conddepth),a
        ret

; ---------------------------------------------------------------- symbols in directives
