        cp '"'
        jr z,is_q
        cp 27h
        ret nz
is_q:   ld c,a
        push hl
        ld b,0
is_len: ld a,(hl)
        or a
        jr z,is_e
        inc hl
        inc b
        jr is_len
is_e:   dec hl
        ld a,(hl)
