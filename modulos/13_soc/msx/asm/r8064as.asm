        call iszero8
        jp z,err_rng
        ld hl,pcv
        ld de,TMPA
        call copy8
        ld hl,TMPA
        ld de,DSN
        ld a,16                 ; MOD
        call ari8
        ld hl,TMPA
        call iszero8
        jr nz,al_r
        ld hl,DSN
        call zero8
        jr ds_go
al_r:   ld hl,DSN
        ld de,TMPA
        ld b,h
        ld c,l
