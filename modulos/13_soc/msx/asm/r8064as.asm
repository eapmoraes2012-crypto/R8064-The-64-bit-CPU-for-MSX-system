        ret

; splitnext: next item of a comma list at HL -> DE (trimmed, 0-terminated). HL after the
; comma. NZ = a comma was found (another item follows, possibly empty)
splitnext:
        call skipsp
        ld (snstart),de
        ld c,0                  ; open quote
        ld b,0                  ; parenthesis depth
sn_l:   ld a,(hl)
        or a
        jr z,sn_end
        inc c
        dec c
        jr z,sn_nq
        cp c                    ; inside quotes
        jr nz,sn_put
        ld c,0
        jr sn_put
sn_nq:  cp '"'
        jr z,sn_q
        cp 27h
        jr nz,sn_p
        push hl                 ; ' : a quote, unless right after a name character of this item
        ld hl,(snstart)
        or a
        sbc hl,de
        pop hl
        ld a,27h
        jr z,sn_q
        dec de
        ld a,(de)
        inc de
        call isid
        ld a,27h
        jr nc,sn_put
sn_q:   ld c,a
        jr sn_put
sn_p:   cp '('
        jr nz,sn_p2
        inc b
        jr sn_put
sn_p2:  cp ')'
        jr nz,sn_p3
        dec b
        jr sn_put
sn_p3:  cp ','
        jr nz,sn_put
        inc b
        dec b
        jr nz,sn_put
        inc hl                  ; comma at depth 0
        call sn_trim
        or 1
        ret
sn_put: ld (de),a
        inc de
        inc hl
        jr sn_l
sn_end: call sn_trim
        xor a
        ret
sn_trim:                        ; drop trailing spaces back to snstart, terminate
        push hl
st_l:   ld hl,(snstart)
        or a
        sbc hl,de
        jr z,st_d
        dec de
        ld a,(de)
        cp ' '
        jr z,st_l
        inc de
st_d:   xor a
        ld (de),a
        pop hl
        ret

; ============================================================================ instructions
instruction:                    ; (formp) = first form of the group
        ; operands
        xor a
        ld (nops),a
        ld hl,(rest)
        ld a,(hl)
        or a
        jr z,in_match
        ld ix,OPS
in_op:  ld a,(nops)
        cp 4
        jp nc,err_ops
        inc a
        ld (nops),a
        ld de,ITEM
        call splitnext
        push af
        push hl
        push ix
        call operand            ; ITEM -> record at IX
        pop ix
        ld de,OPSZ
        add ix,de
        pop hl
        pop af
        jr nz,in_op
in_match:
        ld hl,(formp)
im_l:   ld a,(hl)
        cp 0FFh
        jp z,err_ops            ; no form matched
        ld (curform),hl
        call matchform          ; Z = match
        jr z,im_ok
        ld hl,(curform)         ; next form: skip header, patterns and template
        call skipform
        jr im_l
im_ok:  call encode
        ld hl,INSBUF
        ld a,(inslen)
        ld b,a
im_e:   ld a,(hl)
        push hl
        push bc
        call emit1
        pop bc
        pop hl
        inc hl
        djnz im_e
        ret

; skipform: HL = form -> HL = next form
skipform:
        inc hl                  ; flags
        ld a,(hl)               ; nops
        inc hl
        add a,a
        ld e,a
        ld d,0
        add hl,de               ; patterns
sf_l:   ld a,(hl)               ; template items
        inc hl
        or a
        ret z
        ld e,a
        ld d,0
        push hl
        ld hl,tpllen-1
        add hl,de
        ld a,(hl)
        pop hl
        ld e,a
        add hl,de
        jr sf_l
tpllen: db 1,0,1,2,3,2,2,2      ; argument bytes of template items 1..8

; mnfind: MN (mnlen) -> HL = first form of the group. Z = not found
mnfind: ld a,(mnlen)
        or a
        ret z
        ld a,(MN)
        sub 'A'
        jr c,mf_no
        cp 26
        jr nc,mf_no
        add a,a
        ld e,a
        ld d,0
        ld hl,MNIDX
        add hl,de
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
mf_g:   ld a,(hl)               ; group name
        or a
        jr z,mf_no
        and 7Fh
        ld c,a
        ld a,(MN)
        cp c
        jr nz,mf_no             ; groups are sorted: past this letter
        push hl
        ld de,MN
        ld a,(mnlen)
        ld b,a
mf_c:   ld a,(hl)
        and 7Fh
        ex de,hl
        cp (hl)
        ex de,hl
        jr nz,mf_skip
        bit 7,(hl)
        inc hl
        inc de
        jr nz,mf_last
        djnz mf_c
        jr mf_skip              ; MN ended before the name
mf_last: dec b
        jr nz,mf_skip           ; name ended before MN
        pop af
        inc hl                  ; skip the size word
        inc hl
        or 1
        ret
mf_skip: pop hl
mf_sk2: bit 7,(hl)
        inc hl
        jr z,mf_sk2
        ld e,(hl)
        inc hl
        ld d,(hl)
        inc hl
        add hl,de
        jr mf_g
mf_no:  xor a
        ret

; ---------------------------------------------------------------- operand parsing
; operand: ITEM -> record at IX (kind, kw, known, value)
operand:
        ld (ix+2),1
        ld hl,ITEM
        call kwfind             ; whole text a keyword?
        jr z,op_nkw
        ld (ix+0),K_KW
        ld (ix+1),a
        ret
op_nkw: ld (ix+1),0
        ld a,(ITEM)
        cp '('
        jp nz,op_imm
        call closes_end
        jp nz,op_imm
        ; "(inner)": copy the inner text, trimmed
        ld hl,ITEM+1
        call skipsp
        ld de,ITEM2
op_ci:  ld a,(hl)
        or a
        jr z,op_ce
        ld (de),a
        inc hl
        inc de
        jr op_ci
op_ce:  dec de                  ; drop the ")" and trailing spaces
op_ct:  dec de
        ld a,(de)
        cp ' '
        jr z,op_ct
        inc de
        xor a
        ld (de),a
        ld hl,ITEM2
        call kwfind
        jr z,op_nind
        ld (ix+0),K_IND
        ld (ix+1),a
        ret
op_nind:
        ld hl,idxnames          ; QIX QIY IX IY followed by + or -
op_x:   ld a,(hl)
        or a
        jr z,op_mem
        ex de,hl                ; DE = table name
        ld hl,ITEM2
        call pfxmatch           ; Z = ITEM2 starts with it; HL after, DE at the number
        jr nz,op_xn
        ld a,(de)
        ld b,a                  ; keyword number
        push bc
        call skipsp
        pop bc
        ld a,(hl)
        cp '+'
        jr z,op_xok
        cp '-'
        jr z,op_xok
        ex de,hl                ; no sign: HL = keyword number of this entry
        inc hl
        jr op_x
op_xn:  ex de,hl                ; next entry
op_xs:  ld a,(hl)
        inc hl
        or a
        jr nz,op_xs
        inc hl
        jr op_x
op_xok: ld (ix+0),K_IDX
        ld (ix+1),b
        push ix
        call eval
        pop ix
        jr op_val
; pfxmatch: Z if text HL starts with the 0-terminated string DE. Z: HL after it, DE at its terminator + 1
pfxmatch:
        push hl
pm_l:   ld a,(de)
        or a
        jr z,pm_y
        cp (hl)
        jr nz,pm_n
        inc hl
        inc de
        jr pm_l
pm_y:   inc de
        pop af                  ; drop the start
        xor a
        ret
pm_n:   pop hl                  ; NZ (DE inside the name)
        or 1
        ret
op_mem: ld (ix+0),K_MEM
        ld hl,ITEM2
        jr op_ev
op_imm: ld (ix+0),K_IMM
        ld hl,ITEM
op_ev:  push ix
        call eval
        pop ix
op_val: ld a,(known)
        ld (ix+2),a
        push ix
        pop de
        inc de
        inc de
        inc de
        ld hl,VAL
        jp copy8
idxnames:
        db "QIX",0,KW_IX
        db "QIY",0,KW_IY
        db "IX",0,KW_IX
        db "IY",0,KW_IY
        db 0

; closes_end: ITEM starts with "(": Z if its matching ")" is the last character
closes_end:
        ld hl,ITEM
        ld b,0                  ; depth
        ld c,0                  ; quote
ce_l:   ld a,(hl)
        or a
        jr z,ce_no
        inc c
        dec c
        jr z,ce_nq
        cp c
        jr nz,ce_n
        ld c,0
        jr ce_n
ce_nq:  cp '"'
        jr z,ce_q
        cp 27h
        jr nz,ce_p
        dec hl                  ; ' after a name character is part of the name
        ld a,(hl)
        inc hl
        call isid
        ld a,27h
        jr nc,ce_n
ce_q:   ld c,a
        jr ce_n
ce_p:   cp '('
        jr nz,ce_p2
        inc b
        jr ce_n
ce_p2:  cp ')'
        jr nz,ce_n
        dec b
        jr nz,ce_n
        inc hl                  ; depth back to 0: must be the end
        ld a,(hl)
        or a
        ret z
        jr ce_no
ce_n:   inc hl
        jr ce_l
ce_no:  or 1
        ret

; kwfind: HL = 0-terminated text -> A = keyword number, NZ; Z = not a keyword
kwfind: ld a,(hl)                ; keywords start with a letter (index by letter)
        sub 'A'
        jr c,kf_none
        cp 26
        jr nc,kf_none
        add a,a
        push hl
        ld e,a
        ld d,0
        ld hl,KWIDX
        add hl,de
        ld e,(hl)
        inc hl
        ld d,(hl)
        pop hl
kf_l:   ld a,(de)
        or a
        ret z
        and 7Fh
        cp (hl)
        jr nz,kf_none           ; past this letter
        push hl
kf_c:   ld a,(de)
        and 7Fh
        cp (hl)
        jr nz,kf_n
        ld a,(de)
        inc de
        inc hl
        bit 7,a
        jr z,kf_c
        ld a,(hl)               ; name ended: text must end too
        or a
        jr nz,kf_n2
        pop hl
        ld a,(de)
        or a                    ; NZ (numbers start at 1)
        ret
kf_n:   ld a,(de)               ; skip the rest of the name
        inc de
        bit 7,a
        jr z,kf_n
kf_n2:  inc de                  ; skip the number
        pop hl
        jr kf_l
kf_none: xor a
        ret

; ---------------------------------------------------------------- form matching
; matchform: (curform) against OPS/nops. Z = match; codes, prefixes, bank set
matchform:
        ld hl,(curform)
        ld a,(hl)
        ld (fflags),a
        inc hl
        ld a,(nops)
        cp (hl)
        ret nz
        inc hl
