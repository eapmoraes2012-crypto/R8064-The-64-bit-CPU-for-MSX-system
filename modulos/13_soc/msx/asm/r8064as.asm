; ============================================================================
; r8064as.asm - R8064AS.COM, R8064 assembler for MSX-DOS (runs on the MSX Z80/R800)
; ----------------------------------------------------------------------------
; Two-pass, table-driven assembler for the full R8064 instruction set (Z80, R800 and the
; R8064 extensions), 64-bit expressions, BIN output, optional listing with symbol table
; and optional send + execute on the R8064 cartridge (ports 0Bh-0Dh, r8064io driver).
;
;   R8064AS file[.ASM] [/L] [/G[mode]]
;      /L        write file.LST (listing + symbols)
;      /G[mode]  after a clean assembly send file.BIN to the R8064 at its start address
;                and execute it (mode 0-4, default 1 = Z80 DRAM); waits for the end
;
; The instruction table r8tab.asm is generated by gen_table.py from r8isa.py; the
; R8064 extension encodings there were checked against the decode ROMs of the RTL.
; Build: sjasmplus --raw=R8064AS.COM r8064as.asm
; ============================================================================

BDOS    equ 0005h
CMDLEN  equ 0080h
CMDTXT  equ 0081h
MAXINC  equ 4                   ; source file levels (main + 3 nested INCLUDE)
CTXSZ   equ 183                 ; file context: pos, count, eof, line (2), name (13), FCB (37), buffer (128)
C_POS   equ 0
C_CNT   equ 1
C_EOF   equ 2
C_LINE  equ 3
C_NAME  equ 5
C_FCB   equ 18
C_BUF   equ 55

; pattern classes (isacore.py)
C_KW    equ 1
C_IND   equ 2
C_R8    equ 3
C_XH    equ 4
C_SS    equ 5
C_QQ    equ 6
C_XY    equ 7
C_RR    equ 8
C_INDRR equ 9
C_U4    equ 10
C_CC    equ 11
C_IMM   equ 12
C_MEM   equ 13
C_REL   equ 14
C_IDX8  equ 15
C_IDXQ  equ 16
C_BIT   equ 17
C_ST    equ 18
C_RST   equ 19
C_VAL   equ 20
; operand kinds
K_KW    equ 0
K_IND   equ 1
K_IDX   equ 2
K_MEM   equ 3
K_IMM   equ 4
OPSZ    equ 12                  ; operand record: kind, kw, known, value (8), spare
; keyword attribute offsets (KWATTR, 10 bytes per id)
A_R8    equ 0
A_RR    equ 1
A_Z16   equ 2
A_QQ    equ 3
A_U4    equ 4
A_CC    equ 5
A_XY    equ 6
A_XHP   equ 7
A_XHC   equ 8
A_ST    equ 9
; error codes
E_SYN   equ 1
E_NUM   equ 2
E_UND   equ 3
E_RNG   equ 4
E_DIV   equ 5
E_UNK   equ 6
E_OPS   equ 7
E_TWICE equ 8
E_PHASE equ 9
E_ORG   equ 10
E_IF    equ 11
E_P1    equ 12
E_BANK  equ 13
E_INCNF equ 14
E_INCDP equ 15
E_LONG  equ 16
E_FULL  equ 17

        org 0100h

; ============================================================================ main
start:  ld hl,(0006h)
        ld sp,hl
        xor a
        ld (lstopt),a
        ld (goopt),a
        ld (GUARD),a
        inc a
        ld (gomode),a
        ld hl,DECD+10
        ld (decp),hl
        call parse_cmd
        call pmsg
        db "R8064AS v1.0 - R8064 assembler",13,10,0
        ; heap for the symbol table: from 'heap' up to top of TPA - 1 KB (stack)
        ld hl,(0006h)
        ld de,-1024
        add hl,de
        ld (heaptop),hl
        ld hl,heap
        ld (heapp),hl
        ld hl,symhash           ; empty hash table
        ld de,symhash+1
        ld bc,127
        ld (hl),0
        ldir
        ld hl,0
        ld (symfirst),hl
        ld (symlast),hl
        ld (errcount),hl
        ; ---- pass 1
        ld a,1
        ld (pass),a
        call do_pass
        ; ---- pass 2
        ld a,2
        ld (pass),a
        ld de,binfcb
        call fcreate
        jp nz,e_crbin
        xor a
        ld (obufn),a
        ld (obufn+1),a
        ld a,(lstopt)
        or a
        jr z,st_nl
        ld de,lstfcb
        call fcreate
        jp nz,e_crlst
        ld hl,0
        ld (lbufn),hl
st_nl:  call do_pass
        call oflush
        ld de,binfcb
        ld c,10h
        call BDOS
        ld a,(lstopt)
        or a
        jr z,st_nl2
        call lst_symbols
        call lflush
        ld de,lstfcb
        ld c,10h
        call BDOS
st_nl2: ; ---- summary
        ld hl,(errcount)
        call pdec16
        call pmsg
        db " error(s), ",0
        ld hl,outlen
        call pdec32
        call pmsg
        db " bytes",0
        ld a,(startset)
        or a
        jr z,st_s1
        call pmsg
        db " at ",0
        ld hl,startpc
        call phex32
        ld a,'h'
        call putc
st_s1:  call crlf
        ld hl,(errcount)
        ld a,h
        or l
        jp nz,exit
        ld a,(goopt)
        or a
        jp z,exit
        call do_go
exit:   ld c,0
        jp BDOS

e_crbin: call pmsg
        db "Cannot create the BIN file",13,10,0
        jr exit
e_crlst: call pmsg
        db "Cannot create the LST file",13,10,0
        jr exit

; ---------------------------------------------------------------- command line
parse_cmd:
        ld a,(CMDLEN)
        ld l,a
        ld h,0
        ld de,CMDTXT
        add hl,de
        ld (hl),0
        ld hl,CMDTXT
        call skipsp
        ld a,(hl)
        or a
        jp z,usage
        cp '/'
        jp z,usage
        ld de,srcname           ; copy the name (to space, / or end), uppercase
        ld b,14
pc_n:   ld a,(hl)
        or a
        jr z,pc_ne
        cp ' '
        jr z,pc_ne
        cp '/'
        jr z,pc_ne
        call upcase
        ld (de),a
        inc de
        inc hl
        djnz pc_n
        jp usage
pc_ne:  xor a
        ld (de),a
pc_o:   call skipsp             ; options
        ld a,(hl)
        or a
        jr z,pc_end
        cp '/'
        jp nz,usage
        inc hl
        ld a,(hl)
        call upcase
        inc hl
        cp 'L'
        jr nz,pc_g
        ld (lstopt),a
        jr pc_o
pc_g:   cp 'G'
        jp nz,usage
        ld (goopt),a
        ld a,(hl)
        sub '0'
        jr c,pc_o
        cp 5
        jr nc,pc_o
        ld (gomode),a
        inc hl
        jr pc_o
pc_end: ; build the FCBs: source (default .ASM), BIN, LST
        ld hl,srcname
        ld de,srcfcb
        call mkfcb
        ld a,(srcfcb+9)
        cp ' '
        jr nz,pc_x
        ld hl,srcfcb+9
        ld (hl),'A'
        inc hl
        ld (hl),'S'
        inc hl
        ld (hl),'M'
pc_x:   ld hl,srcfcb
        ld de,binfcb
        ld bc,12
        ldir
        ld hl,srcfcb
        ld de,lstfcb
        ld bc,12
        ldir
        ld hl,binfcb+9
        ld (hl),'B'
        inc hl
        ld (hl),'I'
        inc hl
        ld (hl),'N'
        ld hl,lstfcb+9
        ld (hl),'L'
        inc hl
        ld (hl),'S'
        inc hl
        ld (hl),'T'
        ret

usage:  call pmsg
        db "R8064AS v1.0 - R8064 assembler for MSX-DOS",13,10
        db "Usage: R8064AS file[.ASM] [/L] [/G[mode]]",13,10
        db " /L        listing and symbols in file.LST",13,10
        db " /G[mode]  send file.BIN to the R8064 and run it",13,10
        db "           (mode 0-4, default 1)",13,10,0
        jp exit

; mkfcb: HL = "[D:]NAME[.EXT]" (0-terminated) -> 37-byte FCB at DE (cleared)
mkfcb:  push hl
        push de
        ld h,d
        ld l,e
        inc de
        ld bc,36
        ld (hl),0
        ldir
        pop de
        push de
        inc de
        ld h,d
        ld l,e
        inc de
        ld bc,10
        ld (hl),' '
        ldir
        pop de
        pop hl
        inc hl
        ld a,(hl)
        dec hl
        cp ':'
        jr nz,mf_n
        ld a,(hl)
        call upcase
        sub 'A'-1
        ld (de),a
        inc hl
        inc hl
mf_n:   push de
        inc de
        ld b,8
        call mf_part
        pop de
        ld a,(hl)
        cp '.'
        ret nz
        inc hl
        push de
        ld a,e
        add a,9
        ld e,a
        ld a,d
        adc a,0
        ld d,a
        ld b,3
        call mf_part
        pop de
        ret
mf_part:
        ld a,(hl)
        or a
        ret z
        cp '.'
        ret z
        cp ' '+1
        ret c
        cp '"'
        ret z
        cp 27h
        ret z
        inc hl
        inc b
        dec b
        jr z,mf_part
        call upcase
        ld (de),a
        inc de
        dec b
        jr mf_part

; ============================================================================ passes
do_pass:
        xor a
        ld hl,pcv
        call zero8
        ld (startset),a
        ld (ended),a
        ld (entryset),a
        ld (conddepth),a
        ld (inclev),a
        ld hl,outlen
        call zero8
        ld hl,srcfcb            ; open the main file in context 0
        ld de,ctx0
        call ctx_open
        jr z,dp_ok
        call pmsg
        db "Source file not found",13,10,0
        jp exit
dp_ok:  ld hl,ctx0
        ld (cur),hl
dp_l:   call getline
        jr nz,dp_line
        ld a,(inclev)           ; end of file: back to the including file
        or a
        jr z,dp_end
        call ctx_close
        ld hl,inclev
        dec (hl)
        ld hl,(cur)
        ld de,-CTXSZ
        add hl,de
        ld (cur),hl
        jr dp_l
dp_line: call doline
        ld a,(ended)
        or a
        jr z,dp_l
dp_end: ; close every open level
dp_c:   call ctx_close
        ld a,(inclev)
        or a
        ret z
        dec a
        ld (inclev),a
        ld hl,(cur)
        ld de,-CTXSZ
        add hl,de
        ld (cur),hl
        jr dp_c

; ---------------------------------------------------------------- file contexts
; ctx_open: HL = 12-byte FCB name (drive, name, ext), DE = context. Z = ok
ctx_open:
        push de
        pop ix
        push hl
        push ix                 ; clear the context header and the FCB
        pop hl
        ld b,C_BUF
co_z:   ld (hl),0
        inc hl
        djnz co_z
        pop hl
        push ix
        pop de
        ex de,hl
        ld bc,C_FCB
        add hl,bc
        ex de,hl
        ld bc,12
        ldir                    ; drive/name/ext into the FCB
        push ix
        pop hl
        ld bc,C_FCB
        add hl,bc
        ex de,hl
        push ix
        ld c,0Fh
        call BDOS
        pop ix
        or a
        ret nz
        ld (ix+C_FCB+14),1      ; record size 1, random record 0
        push ix                 ; name for messages: "NAME.EXT"
        pop hl
        ld de,C_NAME
        add hl,de
        ex de,hl
        push ix
        pop hl
        ld bc,C_FCB+1
        add hl,bc
        ld b,8
co_n:   ld a,(hl)
        cp ' '
        jr z,co_n2
        ld (de),a
        inc de
co_n2:  inc hl
        djnz co_n
        ld a,'.'
        ld (de),a
        inc de
        ld b,3
co_e:   ld a,(hl)
        cp ' '
        jr z,co_e2
        ld (de),a
        inc de
co_e2:  inc hl
        djnz co_e
        xor a
        ld (de),a
        ret                     ; Z

ctx_close:
        ld hl,(cur)
        ld de,C_FCB
        add hl,de
        ex de,hl
        ld c,10h
        jp BDOS

; getch: next character of the current file. Cy = 1 at end of file
getch:  ld ix,(cur)
        ld a,(ix+C_POS)
        cp (ix+C_CNT)
        jr c,gc_have
        ld a,(ix+C_EOF)
        or a
        scf
        ret nz
        push ix                 ; read the next block
        pop hl
        ld de,C_BUF
        add hl,de
        ex de,hl
        ld c,1Ah
        call BDOS
        ld hl,(cur)
        ld de,C_FCB
        add hl,de
        ex de,hl
        ld hl,128
        ld c,27h
        call BDOS
        ld ix,(cur)
        ld a,l
        or a
        jr nz,gc_got
        ld (ix+C_EOF),1
        scf
        ret
gc_got: ld (ix+C_CNT),a
        ld (ix+C_POS),0
gc_have: ld e,(ix+C_POS)
        inc (ix+C_POS)
        ld d,0
        push ix
        pop hl
        add hl,de
        ld de,C_BUF
        add hl,de
        ld a,(hl)
        cp 1Ah
        jr nz,gc_ok
        ld (ix+C_EOF),1         ; ^Z: end of file
        ld a,(ix+C_CNT)
        ld (ix+C_POS),a
        scf
        ret
gc_ok:  or a
        ret

; getline: next line into RAWLINE (0-terminated, CR removed). Z = end of file (no line)
getline:
        ld hl,RAWLINE
        ld b,0                  ; characters stored
        ld c,0                  ; 1 = something read
gl_l:   push hl
        push bc
        call getch
        pop bc
        pop hl
        jr c,gl_eof
        ld c,1
        cp 10
        jr z,gl_end
        cp 13
        jr z,gl_l
        inc b
        jr z,gl_full
        ld (hl),a
        inc hl
        jr gl_l
gl_full: dec b
        jr gl_l
gl_eof: ld a,c
        or a
        ret z                   ; nothing read: end of file
gl_end: ld (hl),0
        ld ix,(cur)
        inc (ix+C_LINE)
        jr nz,gl_e2
        inc (ix+C_LINE+1)
gl_e2:  or 1                    ; NZ
        ret

; ============================================================================ one line
doline: ld (errsp),sp
        ld hl,0
        ld (evtrap),hl
        xor a
        ld (lerr),a
        ld (lbn),a
        ld (lnoaddr),a
        ld (lequ),a
        ld (lshort),a
        ld hl,pcv
        ld de,lpc
        call copy8
        call prepline
        call parseline
dl_done:
        ld a,(pass)
        cp 2
        ret nz
        ld a,(lstopt)
        or a
        ret z
        jp lst_line

; error: A = code. Abandons the line (SP back to doline)
error:  ld sp,(errsp)
        ld c,a
        ld hl,(evtrap)
        ld a,h
        or l
        jr z,er_n
        ld de,0
        ld (evtrap),de
        jp (hl)
er_n:   ld a,c
        ld (lerr),a
        ld b,a
        ld a,(pass)
        cp 2
        jr nz,dl_done
        ld hl,(errcount)
        inc hl
        ld (errcount),hl
        push bc
        ld hl,(cur)             ; "NAME.EXT(line): message"
        ld de,C_NAME
        add hl,de
        call pstr
        ld a,'('
        call putc
        ld ix,(cur)
        ld l,(ix+C_LINE)
        ld h,(ix+C_LINE+1)
        call pdec16
        call pmsg
        db "): ",0
        pop bc
        ld a,b
        call errtext
        call pstr
        call crlf
        jr dl_done

errtext:                        ; A = code -> HL = message
        ld hl,errmsgs
        dec a
        add a,a
        ld e,a
        ld d,0
        add hl,de
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        ret
errmsgs: dw m_e1,m_e2,m_e3,m_e4,m_e5,m_e6,m_e7,m_e8,m_e9,m_e10,m_e11,m_e12,m_e13,m_e14,m_e15,m_e16,m_e17
m_e1:   db "syntax error",0
m_e2:   db "bad number",0
m_e3:   db "undefined symbol",0
m_e4:   db "value out of range",0
m_e5:   db "division by zero",0
m_e6:   db "unknown instruction",0
m_e7:   db "invalid operands",0
m_e8:   db "symbol defined twice",0
m_e9:   db "phase error",0
m_e10:  db "ORG backwards",0
m_e11:  db "IF/ELSE/ENDIF mismatch",0
m_e12:  db "value must be known in pass 1",0
m_e13:  db "bank registers mixed",0
m_e14:  db "include file not found",0
m_e15:  db "include nesting too deep",0
m_e16:  db "name too long",0
m_e17:  db "symbol table full",0

err_syn: ld a,E_SYN
        jp error
err_num: ld a,E_NUM
        jp error
err_rng: ld a,E_RNG
        jp error
err_ops: ld a,E_OPS
        jp error
err_p1: ld a,E_P1
        jp error

; prepline: RAWLINE -> LINE: comment removed, tabs -> spaces, uppercase outside quotes.
; A quote ' right after a name character belongs to the name (AF', BC'...).
prepline:
        ld hl,RAWLINE
        ld de,LINE
        ld c,0                  ; open quote
        ld b,' '                ; previous character
pp_l:   ld a,(hl)
        or a
        jr z,pp_end
        inc hl
        cp 9
        jr nz,pp_1
        ld a,' '
pp_1:   inc c
        dec c
        jr z,pp_out
        cp c                    ; inside quotes: copy as is
        jr nz,pp_st
        ld c,0
        jr pp_st
pp_out: cp ';'
        jr z,pp_end
        cp '"'
        jr z,pp_q
        cp 27h
        jr nz,pp_u
        push af
        ld a,b
        call isid
        jr nc,pp_q1             ; after a name character: part of the name
        pop af
        jr pp_q
pp_q1:  pop af
        jr pp_st
pp_q:   ld c,a
        jr pp_st
pp_u:   call upcase
pp_st:  ld (de),a
        inc de
        ld b,a
        jr pp_l
pp_end: xor a
        ld (de),a
        ret

; isid: A in name characters (A-Z a-z 0-9 _ . ? @ $)? Cy = 0 yes, Cy = 1 no. A is kept
isid:   push af
        call upcase
        cp 'A'
        jr c,is_d
        cp 'Z'+1
        jr c,is_y
is_d:   cp '0'
        jr c,is_o
        cp '9'+1
        jr c,is_y
is_o:   cp '_'
        jr z,is_y
        cp '.'
        jr z,is_y
        cp '?'
        jr z,is_y
        cp '@'
        jr z,is_y
        cp '$'
        jr z,is_y
        pop af
        scf
        ret
is_y:   pop af
        or a
        ret

; ---------------------------------------------------------------- parse a line
parseline:
        xor a
        ld (lablen),a
        ld (mnlen),a
        ld hl,LINE
        ld a,(hl)
        or a
        jp z,pl_mn
        cp ' '
        jr z,pl_ind
        ; label in column 1
        ld de,LABEL
        call getname0           ; B = length, HL after
        ld a,b
        or a
        jp z,err_syn
        cp 33
        ld a,E_LONG
        jp nc,error
        ld a,b
        ld (lablen),a
        ld a,(hl)
        cp ':'
        jr nz,pl_mn
        inc hl
        jr pl_mn
pl_ind: call skipsp             ; indented "label:" ?
        push hl
        ld de,LABEL
        call getname0
        ld a,(hl)
        cp ':'
        jr nz,pl_nol
        ld a,b
        or a
        jr z,pl_nol
        cp 33
        ld a,E_LONG
        jp nc,error
        inc hl
        pop af                  ; drop the saved pointer
        ld a,b
        ld (lablen),a
        jr pl_mn
pl_nol: pop hl
pl_mn:  call skipsp
        ld de,MNRAW             ; mnemonic / directive; leading dots are ignored
        call getname0
        ld (rest),hl
        ld a,b
        cp 34
        jr c,pl_m1
        ld b,33
pl_m1:  push hl
        ld hl,MNRAW
pl_m2:  ld a,b
        or a
        jr z,pl_m3
        ld a,(hl)
        cp '.'
        jr nz,pl_m3
        inc hl
        dec b
        jr pl_m2
pl_m3:  ld a,b
        ld (mnlen),a
        ld de,MN
        ld c,b
        ld b,0
        inc bc
        ldir                    ; with the terminator
        pop hl
        call skipsp
        ld (rest),hl
        ld a,(mnlen)
        or a
        jr nz,pl_cond
        ld a,(hl)               ; "label = expr"
        cp '='
        jr nz,pl_cond
        inc hl
        call skipsp
        ld (rest),hl
        ld hl,d_equ
        ld de,MN
        ld bc,4
        ldir
        ld a,3
        ld (mnlen),a
pl_cond:
        ; conditional assembly
        ld a,(MN)
        cp 'I'
        jr z,pl_c1
        cp 'E'
        jp nz,pl_c2
pl_c1:  ld hl,d_if
        call mneq
        jp z,dir_if
        ld hl,d_ifdef
        call mneq
        jp z,dir_ifdef
        ld hl,d_ifndef
        call mneq
        jp z,dir_ifndef
        ld hl,d_else
        call mneq
        jp z,dir_else
        ld hl,d_endif
        call mneq
        jp z,dir_endif
pl_c2:  call isactive
        jr z,pl_inact
        ld a,(MN)
        cp 'E'
        jr nz,pl_c3
        ld hl,d_equ
        call mneq
        jp z,dir_equ
pl_c3:
        ld a,(lablen)           ; a label takes the current PC
        or a
        jr z,pl_nl
        ld hl,pcv
        call deflabel
pl_nl:  ld a,(mnlen)
        or a
        jr nz,pl_nl2
        ld a,(lablen)           ; nothing on the line: no address in the listing
        or a
        ret nz
        inc a
        ld (lnoaddr),a
        ret
pl_nl2: call mnfind              ; an instruction? (no directive has an instruction name)
        jr z,pl_dir
        ld (formp),hl
        jp instruction
pl_dir:
        ld hl,dirtab            ; directives
pl_d:   ld a,(hl)
        or a
        jr z,pl_ins
        ld c,a
        ld a,(MN)
        cp c
        jr nz,pl_ds
        push hl
        call mneq
        pop hl
        jr z,pl_dgo
pl_ds:  ld a,(hl)               ; skip name and handler
        inc hl
        or a
        jr nz,pl_ds
        inc hl
        inc hl
        jr pl_d
pl_dgo: ld a,(hl)
        inc hl
        or a
        jr nz,pl_dgo
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        jp (hl)
pl_inact:
        ld a,1
        ld (lnoaddr),a
        ret
pl_ins: ld a,E_UNK
        jp error

; mneq: HL = 0-terminated directive name; Z if MN equals it
mneq:   ld de,MN
        ld a,(mnlen)
        ld b,a
