dir_include:
        ld hl,(rest)            ; name without quotes and spaces
        ld de,ITEM
inc_c:  ld a,(hl)
        or a
        jr z,inc_e
        inc hl
        cp '"'
        jr z,inc_c
        cp 27h
        jr z,inc_c
        cp ' '
        jr z,inc_c
        ld (de),a
        inc de
        jr inc_c
inc_e:  xor a
        ld (de),a
        ld a,(inclev)
        cp MAXINC-1
        ld a,E_INCDP
        jp nc,error
        ld hl,ITEM
        ld de,INCFCB
