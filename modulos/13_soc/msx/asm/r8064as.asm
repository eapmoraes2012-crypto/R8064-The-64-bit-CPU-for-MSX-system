        ld e,a
        ld d,0
        ld hl,LBYTES
        add hl,de
        ld a,(lcnt)
        sub e
        jr nc,l6_n
        xor a
l6_n:   cp 7
        jr c,l6_m
        ld a,6
l6_m:   ld c,a                  ; bytes to print
        ld b,6
l6_l:   ld a,c
        or a
        jr z,l6_sp
        dec c
        ld a,(hl)
        inc hl
        call lhex8
        call lspc
        djnz l6_l
        ret
l6_sp:  call lspc
        call lspc
        call lspc
        djnz l6_l
        ret

; lst_symbols: symbol table in definition order
lst_symbols:
        call lcrlf
        ld hl,m_syms
        call lstr
        ld hl,(symfirst)
ls_l:   ld a,h
        or l
        ret z
        push hl
        ld de,13
        add hl,de
        ld b,(hl)               ; name
        inc hl
        ld c,b
ls_n:   ld a,(hl)
        call lputc
        inc hl
        djnz ls_n
        ld a,34
        sub c
        ld b,a
ls_p:   call lspc
        djnz ls_p
        pop hl
        push hl
        inc hl                  ; value: 8 or 16 digits
        push hl
        ld de,4
        add hl,de
        call lhex_nz            ; Z if the high 32 bits are zero
        pop hl
        jr z,ls_lo
        push hl
        ld de,4
        add hl,de
        call lhex32
        pop hl
ls_lo:  call lhex32
        call lcrlf
        pop hl
        ld de,11
        add hl,de
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        jr ls_l
lhex_nz: ld a,(hl)
        inc hl
        or (hl)
        inc hl
        or (hl)
        inc hl
        or (hl)
        ret
m_syms: db "Symbols:",13,10,0

; ============================================================================ expressions
; eval: HL = 0-terminated text -> VAL (8 bytes), known (1/0). Errors go to 'error'
eval:   ld (ep),hl
        ld a,1
        ld (known),a
        ld ix,VSTK
        ld hl,D_OR
        call lvl
        call peekc
        or a
        jp nz,err_syn
        ld hl,VSTK
        ld de,VAL
        jp copy8

peekc:  ld hl,(ep)              ; skip spaces; A = character, HL = pointer
pk_l:   ld a,(hl)
        cp ' '
        jr nz,pk_e
        inc hl
        jr pk_l
pk_e:   ld (ep),hl
        ret

; level descriptors: next level (0 = unary), then operators: length, text, code (+80h: word
; operator, must not be followed by a name character), 0
D_OR:   dw D_XOR
        db 1,"|",1, 2,"OR",81h, 0
D_XOR:  dw D_AND
        db 1,"^",2, 3,"XOR",82h, 0
D_AND:  dw D_EQ
        db 1,"&",3, 3,"AND",83h, 0
D_EQ:   dw D_REL
        db 2,"==",4, 2,"!=",5, 2,"<>",5, 1,"=",17, 0
D_REL:  dw D_SH
        db 2,"<=",8, 2,">=",9, 1,"<",6, 1,">",7, 0
D_SH:   dw D_ADD
        db 2,"<<",10, 2,">>",11, 3,"SHL",8Ah, 3,"SHR",8Bh, 0
D_ADD:  dw D_MUL
        db 1,"+",12, 1,"-",13, 0
D_MUL:  dw 0
        db 1,"*",14, 1,"/",15, 1,"%",16, 3,"MOD",90h, 0

; lvl: HL = descriptor, IX = result slot
lvl:    push hl
        call lvl_next
lv_l:   pop hl
        push hl
        call matchop            ; NZ: A = operator code
        jr z,lv_end
        push af
        ld de,8
        add ix,de
        pop af
        pop hl
        push hl
        push af
        call lvl_next
        ld de,-8
        add ix,de
        pop af
        call binop
        jr lv_l
lv_end: pop hl
        ret
lvl_next:
        ld e,(hl)
        inc hl
        ld d,(hl)
        ld a,d
        or e
        jp z,unary
        ex de,hl
        jr lvl

; matchop: HL = descriptor. NZ + A = code (text advanced) or Z
matchop:
        inc hl
        inc hl
        push hl
        call peekc
        pop de                  ; DE = operator list, HL = text
        or a                    ; end of the text: no operator (fast path)
        ret z
        cp ')'
        jr z,mo_none
        cp ','
        jr z,mo_none
mo_l:   ld a,(de)
        or a
        ret z
        ld b,a                  ; length
        inc de
        push hl
        push de
mo_c:   ld a,(de)
        cp (hl)
        jr nz,mo_n
        inc hl
        inc de
        djnz mo_c
        ld a,(de)               ; code
        bit 7,a
        jr z,mo_sym
        ld a,(hl)               ; word: next char must not be a name character
        call isid
        jr nc,mo_n
        ld a,(de)
        and 7Fh
        jr mo_ok
mo_sym: cp 3                    ; exclusions: "&H" (hex), "<" before < >, ">" before >, "=" before =
        jr nz,mo_s2
        ld c,'H'
        jr mo_x
mo_s2:  cp 6
        jr nz,mo_s3
        ld a,(hl)
        cp '<'
        jr z,mo_n
        ld c,'>'
        jr mo_x
mo_s3:  cp 7
        jr nz,mo_s4
        ld c,'>'
        jr mo_x
mo_s4:  cp 17
        jr nz,mo_ok0
        ld c,'='
mo_x:   ld a,(hl)
        cp c
        jr z,mo_n
mo_ok0: ld a,(de)
mo_ok:  pop de
        pop de
        ld (ep),hl
        or a                    ; codes are nonzero: NZ
        ret
mo_n:   pop de                  ; next operator: DE = its text, HL = text
        pop hl
        dec de
        ld a,(de)               ; length
        inc de
        add a,e
        ld e,a
        jr nc,mo_sk
        inc d
mo_sk:  inc de                  ; skip the code
        jr mo_l
mo_none: xor a
        ret

; binop: A = code; (IX) = (IX) op (IX+8)
binop:  cp 17
        jr nz,bo_t
        ld a,4                  ; "=" is "=="
bo_t:   dec a
        add a,a
        ld e,a
        ld d,0
        ld hl,bintab
        add hl,de
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        push hl
        push ix                 ; HL = A operand, DE = B operand
        pop hl
        ld de,8
        add hl,de
        ex de,hl
        push ix
        pop hl
        ret                     ; jump to the routine
bintab: dw b_or,b_xor,b_and,b_eq,b_ne,b_lt,b_gt,b_le,b_ge,b_shl,b_shr,b_add,b_sub,b_mul,b_div,b_mod

b_or:   ld b,8
bor_l:  ld a,(de)
        or (hl)
        ld (hl),a
        inc hl
        inc de
        djnz bor_l
        ret
b_xor:  ld b,8
bxo_l:  ld a,(de)
        xor (hl)
        ld (hl),a
        inc hl
        inc de
        djnz bxo_l
        ret
b_and:  ld b,8
ban_l:  ld a,(de)
        and (hl)
        ld (hl),a
        inc hl
        inc de
        djnz ban_l
        ret
b_add:  ex de,hl
        ld b,8
        or a
bad_l:  ld a,(de)
        adc a,(hl)
        ld (de),a
        inc hl
        inc de
        djnz bad_l
        ret
b_sub:  ld b,h
        ld c,l
        jp sub8                 ; (BC) = (HL) - (DE)
b_eq:   call cmpu8
        ld a,0
        jr nz,bset
        inc a
        jr bset
b_ne:   call cmpu8
        ld a,0
        jr z,bset
        inc a
        jr bset
b_lt:   call cmps8              ; Cy: A < B
        ld a,0
        adc a,a
        jr bset
b_ge:   call cmps8
        ld a,1
        sbc a,0
        jr bset
b_gt:   ex de,hl                ; A > B  <=>  B < A
        call cmps8
        ld a,0
        adc a,a
        jr bset
b_le:   ex de,hl
        call cmps8
        ld a,1
        sbc a,0
bset:   push af                 ; (IX) = A (0/1)
        push ix
        pop hl
        call zero8
        pop af
        ld (ix+0),a
        ret
b_shl:  call shcount            ; B = count, or Z: >= 64
        jp z,b_zero
sl_l:   push ix
        pop hl
        call shl8
        djnz sl_l
        ret
b_shr:  call shcount
        jp z,b_zero
sr_l:   push ix
        pop hl
        call shr8
        djnz sr_l
        ret
shcount:                        ; DE = count operand. NZ + B = count 1..63; count 0: returns to the caller's caller
        ex de,hl
        inc hl
        call ec_hi0             ; bytes 1..7 zero?
        jr nz,shc_big
        ld de,-8
        add hl,de
        ld a,(hl)
        cp 64
        jr nc,shc_big
        or a
        jr z,shc_0
        ld b,a
        or 1
        ret
shc_0:  pop hl                  ; shift by 0: nothing to do
        ret
shc_big: xor a
        ret
b_zero: push ix
        pop hl
        jp zero8
b_mul:  push hl                 ; P = 0; 64 times: if B&1: P += A; A <<= 1; B >>= 1
        push de
        ld hl,TMPP
        call zero8
        pop de
        pop hl
        ld b,64
bm_l:   push bc
        push hl
        push de
        ld a,(de)
        and 1
        jr z,bm_n
        push de                 ; P += A
        ld de,TMPP
        ex de,hl                ; HL = P, DE = A
        ld b,8
        or a
bm_a:   ld a,(de)
        adc a,(hl)
        ld (hl),a
        inc hl
        inc de
        djnz bm_a
        pop de
bm_n:   pop de
        pop hl
        push hl
        push de
        call shl8               ; A <<= 1
        ex de,hl
        call shr8               ; B >>= 1
        pop de
        pop hl
        pop bc
        djnz bm_l
        ex de,hl                ; result -> (IX)
        ld hl,TMPP
        push ix
        pop de
        jp copy8
b_div:  call divmod
        ret                     ; quotient already in (IX)
b_mod:  call divmod
        ld hl,TMPR
        push ix
        pop de
        jp copy8
; divmod: (IX) / (IX+8) unsigned -> quotient in (IX), remainder in TMPR
divmod: push ix
        pop hl
        ld de,8
        add hl,de
        call iszero8
        jr nz,dm_go
        ld a,(pass)             ; division by zero: error in pass 2, 0 in pass 1
        cp 2
        ld a,E_DIV
        jp z,error
        push ix
        pop hl
        call zero8
        ld hl,TMPR
        jp zero8
dm_go:  ld hl,TMPR
        call zero8
        ld b,64
dm_l:   push bc
        push ix                 ; (R:Q) <<= 1
        pop hl
        call shl8
        ld hl,TMPR
        rl (hl)
        ld b,7
dm_r:   inc hl
        rl (hl)
        djnz dm_r
        ld hl,TMPR              ; R >= D ?
        push ix
        pop de
        ld a,e
        add a,8
        ld e,a
        jr nc,dm_c
        inc d
dm_c:   push de
        call cmpu8
        pop de
        jr c,dm_n
        ld hl,TMPR
        ld b,h
        ld c,l
        call sub8               ; R -= D
        set 0,(ix+0)
dm_n:   pop bc
        djnz dm_l
        ret

; unary operators and atoms, into (IX)
unary:  call peekc
        cp '-'
        jr nz,un_1
        inc hl
        ld (ep),hl
        call unary
        push ix
        pop hl
        jp neg8
un_1:   cp '+'
        jr nz,un_2
        inc hl
        ld (ep),hl
        jr unary
un_2:   cp '~'
        jr nz,un_3
        inc hl
        ld (ep),hl
        call unary
        jr un_not
un_3:   cp '!'
        jr nz,un_4
        inc hl
        ld (ep),hl
        call unary
        push ix
        pop hl
        call iszero8
        ld a,0
        jr nz,un_3b
        inc a
un_3b:  jp bset
un_4:   ld de,w_not
        call takew
        jr nz,un_5
        call unary
un_not: push ix
        pop hl
        ld b,8
un_nl:  ld a,(hl)
        cpl
        ld (hl),a
        inc hl
        djnz un_nl
        ret
un_5:   ld de,w_high
        call takew
        jr nz,un_6
        call unary
        ld a,(ix+1)
        jp bset
un_6:   ld de,w_low
        call takew
        jr nz,un_7
        call unary
        ld a,(ix+0)
        jp bset
un_7:   call peekc
        cp '('
        jr nz,atom
        inc hl
        ld (ep),hl
        ld hl,D_OR
        call lvl
        call peekc
        cp ')'
        jp nz,err_syn
        inc hl
        ld (ep),hl
        ret
w_not:  db "NOT",0
w_high: db "HIGH",0
w_low:  db "LOW",0
; takew: DE = word; Z if the text at ep is that word (not followed by a name character); ep advanced
takew:  call peekc
tw_l:   ld a,(de)
        or a
        jr z,tw_e
        cp (hl)
        ret nz
        inc hl
        inc de
        jr tw_l
tw_e:   ld a,(hl)
        call isid
        jr nc,tw_no
        ld (ep),hl
        xor a
        ret
tw_no:  or 1
        ret

atom:   push ix                 ; (IX) = 0
        pop hl
        call zero8
        call peekc
        cp 27h
        jr z,at_ch
        cp '"'
        jr nz,at_1
at_ch:  ld c,a                  ; 'x' or "x"
        inc hl
        ld b,(hl)
        inc hl
        ld a,(hl)
        cp c
        jp nz,err_syn
        ld a,b
        or a
        jp z,err_syn
        inc hl
        ld (ep),hl
        ld (ix+0),b
        ret
at_1:   cp '$'
        jr nz,at_2
        inc hl
        ld a,(hl)
        call hexval
        jr nc,at_hx             ; $ + hex digit: hex number
        ld (ep),hl              ; $ = address of the line
        ld hl,lpc
        push ix
        pop de
        jp copy8
at_hx:  ld c,16
        jp digits
at_2:   cp '%'
        jr nz,at_3
        inc hl
        ld c,2
        jp digits
at_3:   cp '&'
        jr nz,at_4
        inc hl
        ld a,(hl)
        cp 'H'
        jp nz,err_syn
        inc hl
        ld c,16
        jp digits
at_4:   cp '0'
        jr c,at_5
        cp '9'+1
        jr nc,at_5
        jp number
at_5:   call isid
        jp c,err_syn
        ; symbol
        ld de,NAMEBUF
        call getname0
        ld (ep),hl
        ld a,b
        cp 33
        ld a,E_LONG
        jp nc,error
        call symfind
        jr z,at_und
        inc hl                  ; value
        push ix
        pop de
        jp copy8
at_und: ld a,(pass)
        cp 2
        ld a,E_UND
        jp z,error
        xor a
        ld (known),a
        ret

; digits: HL = text, C = base (2 or 16): at least one digit -> (IX)
digits: ld b,0
dg_l:   ld a,(hl)
        call hexval             ; Cy = 1 not a hex digit, A = value
        jr c,dg_e
        cp c
        jr nc,dg_e
        call mulbase            ; (IX) = (IX) * C + A
        inc hl
        inc b
        jr dg_l
dg_e:   ld a,b
        or a
        jp z,err_num
        ld (ep),hl
        ret
hexval: cp '0'                  ; A = '0'-'9','A'-'F' -> 0-15, Cy = 0; else Cy = 1
        jr c,hv_n
        cp '9'+1
        jr c,hv_d
        cp 'A'
        jr c,hv_n
        cp 'F'+1
        jr nc,hv_n
        sub 'A'-10
        or a
        ret
hv_d:   sub '0'
        or a
        ret
hv_n:   scf
        ret

; number: token of [0-9A-Z] at HL; base by prefix/suffix (0x, ...H, 0b..., ...B, ...D)
number: ld (numst),hl
        ld b,0
nb_l:   ld a,(hl)               ; token length
        cp '0'
        jr c,nb_e
        cp '9'+1
        jr c,nb_c
        cp 'A'
        jr c,nb_e
        cp 'Z'+1
        jr nc,nb_e
nb_c:   inc hl
        inc b
        jr nb_l
nb_e:   ld (ep),hl
        ld a,b
        ld (numlen),a
        dec hl
        ld a,(hl)               ; last character
        ld (numlast),a
        ld hl,(numst)
        inc hl
        ld a,(hl)               ; second character
        dec hl
        ld c,a
        ld a,(hl)
        cp '0'
        jr nz,nb_h
        ld a,c
        cp 'X'
        jr nz,nb_h
        ld a,(numlen)           ; 0x...
        sub 2
        inc hl
        inc hl
        ld c,16
        jr nb_conv
nb_h:   ld a,(numlast)
        cp 'H'
        jr nz,nb_b0
        ld a,(numlen)
        dec a
        ld c,16
        jr nb_conv
nb_b0:  ld a,(hl)               ; 0b... with only 0/1 after
        cp '0'
        jr nz,nb_b1
        ld a,(numlen)
        cp 3
        jr c,nb_b1
        ld a,c
        cp 'B'
        jr nz,nb_b1
        push hl
        inc hl
        inc hl
        ld a,(numlen)
        sub 2
        call allbin
        pop hl
        jr nz,nb_b1
        inc hl
        inc hl
        ld a,(numlen)
        sub 2
        ld c,2
        jr nb_conv
nb_b1:  ld a,(numlast)          ; ...B with only 0/1 before
        cp 'B'
        jr nz,nb_d
        ld a,(numlen)
        dec a
        push hl
        call allbin
        pop hl
        jr nz,nb_d
        ld a,(numlen)
        dec a
        ld c,2
        jr nb_conv
nb_d:   ld a,(numlast)
        cp 'D'
        ld a,(numlen)
        jr nz,nb_10
        dec a
nb_10:  ld c,10
; nb_conv: HL = first digit, A = digit count, C = base -> (IX); every character must be a digit
nb_conv:
        or a
        jp z,err_num
        ld b,a
nc_l:   ld a,(hl)
        call hexval
        jp c,err_num
        cp c
        jp nc,err_num
        call mulbase
        inc hl
        djnz nc_l
        ret
allbin: ld b,a                  ; A characters at HL all 0/1? Z = yes
        or a
        jr z,ab_y
ab_l:   ld a,(hl)
        cp '0'
        jr z,ab_n
        cp '1'
        ret nz
ab_n:   inc hl
        djnz ab_l
ab_y:   xor a
        ret

; mulbase: (IX) = (IX) * C + A  (C = 2, 10 or 16)
mulbase:
        push hl
        push bc
        push af
        push ix
        pop hl
        ld de,TMPP
        call copy8              ; TMPP = x
        ld a,c
        cp 10
        jr z,mb_10
        ld b,1                  ; base 2: 1 shift, base 16: 4 shifts
        cp 2
        jr z,mb_s
        ld b,4
mb_s:   push ix
        pop hl
        call shl8
        djnz mb_s
        jr mb_add
mb_10:  push ix                 ; x*10 = x*8 + x*2
        pop hl
        call shl8
        call shl8
        call shl8
        ld hl,TMPP
        call shl8
        push ix
        pop hl
        ld de,TMPP
        ex de,hl
        ld b,8
        or a
mb_a:   ld a,(hl)
        ex de,hl
        adc a,(hl)
        ld (hl),a
        ex de,hl
        inc hl
        inc de
        djnz mb_a
mb_add: pop af                  ; + digit
        push ix
        pop hl
        call add8a
        pop bc
        pop hl
        ret

; ============================================================================ symbol table
; entry: +0 flags (b0 defined, b1 defined in pass 1), +1 value (8), +9 hash next, +11 order next,
;        +13 length, +14 name
; symhash: hash of NAMEBUF -> HL = bucket
symhash_: ld hl,NAMEBUF
        ld c,0
sh_l:   ld a,(hl)
        or a
        jr z,sh_e
        ld b,a
        ld a,c
        add a,a
        add a,c
        add a,b
        ld c,a
        inc hl
        jr sh_l
sh_e:   ld a,c
        and 63
        add a,a
        ld e,a
        ld d,0
        ld hl,symhash
        add hl,de
        ret
; symfind: NAMEBUF -> HL = entry, NZ; Z = not found
symfind:
        call symhash_
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
sf_n:   ld a,h
        or l
        ret z
        push hl
        ld de,13
        add hl,de
        ld b,(hl)               ; length
        inc hl
        ld de,NAMEBUF
sf_c:   ld a,(de)
        cp (hl)
        jr nz,sf_no
        inc hl
        inc de
        djnz sf_c
        ld a,(de)
        or a
        jr nz,sf_no
        pop hl
        or 1
        ret
sf_no:  pop hl
        ld de,9
        add hl,de
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        jr sf_n
; syminsert: NAMEBUF (not present) -> HL = new entry (flags 0, value 0)
syminsert:
        ld hl,NAMEBUF           ; length
        ld b,0
si_len: ld a,(hl)
        or a
        jr z,si_l2
        inc hl
        inc b
        jr si_len
si_l2:  ld hl,(heapp)
        push hl                 ; new entry
        ld e,b
        ld d,0
        add hl,de
        ld de,14
        add hl,de
        ex de,hl                ; DE = new heap pointer
        ld hl,(heaptop)
        or a
        sbc hl,de
        jp c,e_full
        ld (heapp),de
        pop hl
        push hl
        ld (hl),0               ; flags + value
        ld d,h
        ld e,l
        inc de
        push bc
        ld bc,8
        ldir
        pop bc
        pop hl
        push hl
        push bc
        call symhash_           ; link at the head of the bucket
        ld e,(hl)
        inc hl
        ld d,(hl)
        pop bc
