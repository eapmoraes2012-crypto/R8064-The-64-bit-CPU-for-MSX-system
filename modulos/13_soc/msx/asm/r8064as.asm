        or a
        jp z,err_syn
        ld hl,(rest)
        call eval
        ld a,1
        ld (lequ),a
        ld a,(known)
        or a
        jr nz,deq_k
        ld a,(pass)
        cp 1
        ret z                   ; not yet known: defined in pass 2
deq_k:  ld hl,VAL
        jp deflabel

; deflabel: define LABEL with the 8-byte value at HL
deflabel:
        ld (dlval),hl
        ld hl,LABEL
        ld de,NAMEBUF
        ld bc,34
        ldir
        call symfind            ; NZ = found, HL = entry
        jr nz,dl_found
        call syminsert
        ld a,(pass)
        ld c,3                  ; bit 0 defined, bit 1 defined in pass 1
        cp 1
        jr z,dl_w
        ld c,1
dl_w:   ld (hl),c
dl_cpy: inc hl
        ex de,hl
        ld hl,(dlval)
        ld bc,8
        ldir
        ret
dl_found:
        ld a,(pass)
        cp 1
        jr nz,dl_cmp
        bit 1,(hl)
        ld a,E_TWICE
        jp nz,error
        ld a,(hl)
        or 3
        ld (hl),a
        jr dl_cpy
dl_cmp: inc hl
        ld de,(dlval)
        ld b,8
dl_c:   ld a,(de)
        cp (hl)
        ld a,E_PHASE
        jp nz,error
        inc hl
        inc de
        djnz dl_c
        ret

; ---------------------------------------------------------------- ORG / data / END / INCLUDE
dir_org:
        ld a,1
        ld (lshort),a
        ld hl,(rest)
        call eval
        ld a,(known)
        or a
        jp z,err_p1
        ld a,(pass)
        cp 2
        jr nz,do_set
        ld a,(startset)
        or a
        jr z,do_set
        ld hl,VAL               ; v < pc: backwards
        ld de,pcv
        call cmpu8              ; Cy if (HL) < (DE)
        ld a,E_ORG
        jp c,error
        ld hl,VAL               ; fill the gap now
        ld de,pcv
        ld bc,TMPA
        call sub8               ; TMPA = VAL - pc
        ld hl,TMPA
        xor a
        call emitn
do_set: ld hl,VAL
        ld de,pcv
        jp copy8

dir_db: call db_init
        ld a,(hl)
        or a
        ret z
ddb_l:  ld de,ITEM
        call splitnext
        push af                 ; NZ = more items
        push hl
        ld hl,ITEM
        call isstring           ; Z = string, HL = first char, B = length
        jr nz,ddb_e
        ld a,b
        or a
        jr z,ddb_n
ddb_s:  ld a,(hl)
        call db_put
        inc hl
        djnz ddb_s
        jr ddb_n
ddb_e:  ld hl,ITEM
        call eval
        ld a,1
        call chkrng             ; pass 2: -128..255
        ld a,(VAL)
        call db_put
ddb_n:  pop hl
        pop af
        jr nz,ddb_l
        jp db_emit
; data lines: every item is evaluated first, the bytes are emitted only if the whole line is right
db_init: ld hl,0
        ld (dbn),hl
        ld hl,(rest)
        ret
db_put: push hl
        push de
        ld hl,(dbn)
        ld de,DBUF
        add hl,de
        ld (hl),a
        ld hl,(dbn)
        inc hl
        ld (dbn),hl
        pop de
        pop hl
        ret
db_emit: ld hl,(dbn)
        ld a,h
        or l
        ret z
        ld b,h
        ld c,l
        ld hl,DBUF
dbe_l:  ld a,(hl)
        push hl
        push bc
        call emit1
        pop bc
        pop hl
        inc hl
        dec bc
        ld a,b
        or c
        jr nz,dbe_l
        ret

; isstring: ITEM is "..." or '...' (length >= 2, not 3, same quote at both ends)? Z = yes
isstring:
