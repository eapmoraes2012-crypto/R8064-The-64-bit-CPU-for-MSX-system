        djnz ddn_b
        pop hl
        pop af
        jr nz,ddn_l
        jp db_emit

dir_ds: xor a
        jr dsal
dir_align:
        ld a,1
dsal:   ld (isalign),a
        ld a,1
        ld (lshort),a
        ld hl,(rest)
        ld de,ITEM
        call splitnext
        push af
        push hl
        ld hl,ITEM
        call eval
        ld a,(known)
        or a
        jp z,err_p1
        ld hl,VAL
        ld de,DSN
        call copy8
        xor a
        ld (dsfill),a
        pop hl
        pop af
        jr z,ds_nf
