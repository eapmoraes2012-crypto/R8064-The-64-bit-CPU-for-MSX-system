# gen_table.py - writes r8tab.asm, the instruction/keyword table of R8064AS.COM, from r8isa.py (through isacore.py).
import os
from isacore import COMPILED, MNEMS, BYMN, KWIDS, KWNUM
from r8isa import KW
here = os.path.dirname(os.path.abspath(__file__))
L = ['; r8tab.asm - GENERATED by gen_table.py from r8isa.py: do not edit', '']
def db(bs): return '        db ' + ','.join('%03Xh' % b for b in bs)
def name(s): return '"%s"+80h' % s if len(s) == 1 else '"%s","%s"+80h' % (s[:-1], s[-1])
# keywords: name, id (1..); attributes per id
L.append('KWTAB:')
kfirst = {}
for n in sorted(KW, key=lambda x: (x[0], x)):
    if n[0] not in kfirst: kfirst[n[0]] = n; L.append('KW_1%s:' % n[0])
    L.append('        db %s,%d' % (name(n).replace('"\'"', "27h"), KWNUM[KW[n]['id']]))
L.append('KWEND:  db 0')
L.append('KWIDX:                  ; first keyword of each letter A..Z')
for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':
    L.append('        dw %s' % ('KW_1' + c if c in kfirst else 'KWEND'))
L.append('KWATTR:                 ; per id: r8, rr (bank<<4 | code), z16 (bank<<4 | code), qq, u4, cc, xy prefix, xh prefix, xh code, st')
for k in KWIDS:
    a = KW[k]; f = lambda x: 0xFF if a.get(x) is None else a[x]
    bank = a.get('bank', 0)
    rr = 0xFF if a.get('rr') is None else (bank << 4 | a['rr'])
    z16 = 0xFF if a.get('z16') is None else (bank << 4 | a['z16'])
    xh = a.get('xh')
    L.append(db([f('r8'), rr, z16, f('qq'), f('u4'), f('cc'), a.get('xy', 0), xh[0] if xh else 0, xh[1] if xh else 0xFF, f('st')]) + '   ; %d %s' % (KWNUM[k], k))
# mnemonic groups
def form_bytes(f):
    b = [(1 if f.bank else 0) | (2 if f.same else 0) | (f.len << 4), len(f.pats)]
    for c, a in f.pats: b += [c, a & 0xFF]
    for it in f.tpl:
        t = it[0]
        if t == 'L': b += [1, it[1]]
        elif t == 'E': b += [2]
        elif t == 'P': b += [3, it[1]]
        elif t == 'F':
            fl = it[2]; assert len(fl) <= 2
            b += [4 if len(fl) == 1 else 5, it[1]] + [k | sh << 4 for k, sh in fl]
        elif t in 'IRD': b += [{'I': 6, 'R': 7, 'D': 8}[t], it[1], it[2]]
    return b + [0]
groups = sorted(MNEMS)
L.append('MNTAB:')
first = {}
total = 0
for m in groups:
    first.setdefault(m[0], m)
    fb = []
    for f in BYMN[m]: fb += form_bytes(f)
    fb.append(0xFF)
    L.append('MN_%s:' % m.replace("'", '_'))
    L.append('        db %s' % name(m)); L.append('        dw %d' % len(fb))
    for i in range(0, len(fb), 16): L.append(db(fb[i:i + 16]))
    total += len(fb)
L.append('        db 0')
L.append('MNIDX:                  ; first group of each letter A..Z')
for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':
    L.append('        dw %s' % ('MN_' + first[c] if c in first else 'MNEND'))
L.append('MNEND:  db 0')
L.append('NKW     equ %d' % len(KWIDS))
for k in ('IX', 'IY', 'A', 'C', 'HL', 'SP', 'AF'):
    L.append('KW_%s   equ %d' % (k, KWNUM[k]))
open(os.path.join(here, 'r8tab.asm'), 'w').write('\n'.join(L) + '\n')
print('mnemonics %d, forms %d, form bytes %d, keywords %d (ids %d)' % (len(groups), len(COMPILED), total, len(KW), len(KWIDS)))
